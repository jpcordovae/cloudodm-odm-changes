#!/usr/bin/env python3
"""The accuracy of a reconstruction at surveyed points it was not fitted to.

A checkpoint is a surveyed point, marked in the photos like a ground control
point, that the adjustment never saw. Here each one is located from its marks
with the reconstruction's own cameras (the rays through the marked pixels are
intersected) and compared with its surveyed position. The differences are the
checkpoint errors: what a surveyor reports as the accuracy of the job.

    checkpoint-report.py --opensfm <project>/opensfm --gcp gcp_list.txt --out <folder>
                         [--title "..."] [--lang en|es|both]

The file is in OpenDroneMap's ground-control format:

    EPSG:32719                      (or a proj string, or "WGS84 UTM 19S")
    x y z pixel_x pixel_y image.jpg name

With `--gcp`, the one file a client uploads, a point whose name starts with CHK
or CHECK is a checkpoint and the rest are control (the engine leaves the
checkpoints out of the adjustment by the same rule: add-checkpoints.py);
`--all-check` treats every point as a checkpoint, for a run that did not use
the file to fit. The two can also be given apart: `--checkpoints file
[--control file]`. Control points are reported beside the checkpoints, for
comparison.

Writes checkpoints.json and checkpoints.pdf in --out (`--lang both`: English as
checkpoints.pdf, Spanish as checkpoints.es.pdf). Exit 0 when a report was
written or the file holds no checkpoint, 2 when no checkpoint is marked in two
photos of the reconstruction, 1 on bad input.

    checkpoint-report.py --self-test
"""
